CLAIMS = []


def claim(where, tex, printed, value=None, step=None, source="", tol=None, rel=None, status=None, note=None,
          occurrence=0, text=None):
    """tex: a snippet of the main.tex line that holds the number (with the number in it); printed: the number as
    printed ('0.21', '1.1--1.2' for a range); value: () -> float or (lo, hi), or None; tol: absolute tolerance
    (default: half a unit of the last printed digit); rel: relative tolerance instead (timings, 'about'); text: () ->
    the regenerated result in words, for statements without a single number."""
    CLAIMS.append(dict(where=where, tex=tex, printed=printed, value=value, step=step, source=source, tol=tol, rel=rel,
                       status=status, note=note, occurrence=occurrence, text=text))


