def find_line(snippet, occurrence=0):
    """1-based line of main.tex where `snippet` starts (it may span lines with '\n'), or None."""
    parts = snippet.split("\n")
    hits = []
    for i in range(len(LINES)):
        if parts[0] in LINES[i] and all(i + k < len(LINES) and parts[k] in LINES[i + k] for k in range(1, len(parts))):
            hits.append(i + 1)
    return hits[occurrence] if len(hits) > occurrence else None


def table_row(label):
    """Table I row -> its cells, read from main.tex."""
    for i, line in enumerate(LINES):
        if line.strip().startswith(label + " ") and "&" in line:
            c = [x.strip() for x in line.replace("\\\\", "").split("&")]
            tip, tip95 = [x.strip() for x in c[3].split("/")]
            return dict(tex=line.split("&")[0] + "&", poses=c[1], plane=c[2], tip=tip, tip95=tip95, rot=c[4],
                        learned=c[5])
    return None


def table2_row(label):
    for line in LINES:
        if line.strip().startswith(label) and "&" in line:
            c = [re.sub(r"\$\^\\dagger\$", "", x).strip() for x in line.replace("\\\\", "").split("&")]
            return dict(tex=line.split("&")[0] + "&", values=c[1:])
    raise KeyError(label)


