def md_escape(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def write_md(rows, meta):
    counts = {s: sum(r["status"] == s for r in rows) for s in STATUSES}
    L = ["# Paper claims: printed vs regenerated", "",
         f"Generated by `scripts/claims.py` on {meta['generated']} from the result files under `results/`; regenerate "
         "everything with `.venv/bin/python scripts/reproduce.py` (fast mode, ~5 min; `--full` adds the multi-hour "
         "jobs). Machine-readable version: `results/claims.json`. Paper: `paper/main.tex` (line numbers below).", "",
         f"**{len(rows)} numbers**: " + ", ".join(f"{counts[s]} {s}" for s in STATUSES) + ".", "",
         "Statuses: **reproduced**, the regenerated value rounds to the printed one (timings and 'about' values within "
         "a stated relative tolerance); **differs**, it does not (difference given); **stored, not re-run**, a stored "
         "result of a multi-hour job produced by the old code and not repeated by this run (Table II PINN rows); "
         "**not reproducible here**, needs SOFA, the raw sweeps or a mesh that is not in the repository; "
         "**hardware pending**, `\\pending` in the paper. Notes marked *W3* give the physics audit's correction "
         "(`reviews/physics_audit.md`) next to the value as the paper defines it.", ""]
    if meta.get("machine"):
        L += [f"Timings in this run: {meta['machine']}.", ""]
    L += ["## What differs", ""]
    for r in rows:
        if r["status"] == "differs":
            d = r["delta"]
            dd = (" / ".join(f"{x:+.3g}" for x in d) if isinstance(d, list) else f"{d:+.3g}") if d is not None else ""
            L.append(f"- **{r['where']}** (main.tex:{r['line']}): printed {r['printed']}, regenerated "
                     f"{r['regenerated_str'] or '-'}" + (f" (difference {dd})" if dd else "") + ". " + (r["note"] or ""))
    L += ["", "## Not reproducible here", ""]
    for r in rows:
        if r["status"] == "not reproducible here":
            L.append(f"- **{r['where']}** (main.tex:{r['line']}): printed {r['printed']}"
                     + (f", value {r['regenerated_str']}" if r["regenerated_str"] and not
                        r["regenerated_str"].startswith("(missing") else "") + ". " + (r["note"] or ""))
    L += ["", "## results/n_transfer.json replaced (2 Nov 2026 run of the packaged code)", "",
          "The stored file predated the 29 Oct gravity-solver convergence fix. It was replaced by a fresh run of the "
          "packaged code at d51a007 (`OMP_NUM_THREADS=8 .venv/bin/python scripts/n_transfer.py --mc "
          "results/mc_std6.json`, ~2 h; the old code at d363e90 gives the same file apart from the `mc` path). What "
          "moved (tip error, mm; none of it is printed in the paper):", "",
          "| test set | model | mean | p95 | max |", "|---|---|---|---|---|",
          "| 2 modules, horizontal x | +L3 local (inside) | 5.417 -> 5.642 | 15.93 -> 19.57 | 21.76 -> 25.16 |",
          "| 2 modules, horizontal x | +L3 local+N (inside) | 5.374 -> 5.386 | 9.735 -> 9.697 | 18.56 -> 18.42 |",
          "| 2 modules, horizontal y | +L3 local (inside) | 6.653 -> 6.878 | 12.40 -> 13.86 | 14.47 -> 15.39 |", "",
          "Everything else moved by less than 0.005 mm (coverage ratios by less than 1e-11). The paper quotes the "
          "'output' coupling and the four-module and hanging sets, which did not change.", "",
          "## Stored result files regenerated by the fast mode (committed 3 Nov 2026)", "",
          "- `results/mc_std6.json`: regenerated with `OMP_NUM_THREADS=1`; theta moves by at most 4e-10 against the "
          "file the paper was made from (BLAS thread count), no printed digit changes. It is bit-identical to the file "
          "the n_transfer run above used.",
          "- `results/mc_std6_reeval.json`: moves by at most 1e-10.",
          "- `results/pinn/exact_global3_2s.json`: bit-identical factors and test errors; now also stores the fit "
          "time; the four-module test, which the old session added in a second step, is now computed by the script.",
          "- `results/mc_ablation.json` (older robot, footnote): identical to 3 decimals except one entry the paper does "
          "not print, '1s (144) + 2s (25)' on four modules: 0.624 -> 1.865 mm (its 1- and 2-module errors are "
          "unchanged, so the fit is the same and the four-module solve differs; the code has changed since 7 Oct). "
          "The two printed entries (6.50 and 0.73 mm) reproduce. Worth a look by the code review (W4).", "",
          "## All numbers", "",
          "| line | where | printed | regenerated | status | step | notes |", "|---|---|---|---|---|---|---|"]
    notes, idx = [], {}
    for r in rows:
        ref = ""
        if r["note"]:
            if r["note"] not in idx:
                notes.append(r["note"])
                idx[r["note"]] = len(notes)
            ref = f"[{idx[r['note']]}](#note-{idx[r['note']]})"
        L.append(f"| {r['line']} | {md_escape(r['where'])} | {md_escape(r['printed'])} | "
                 f"{md_escape(r['regenerated_str'])} | {r['status']} | {r['step'] or '-'} | {ref} |")
    L += ["", "## Notes", ""]
    for k, n in enumerate(notes, 1):
        L.append(f"<a id=\"note-{k}\"></a>{k}. {n}")
    L += ["", "## Steps and commands", "",
          "Run all with `.venv/bin/python scripts/reproduce.py` (or one with `--only <step>`); each command can also "
          "be run by hand from the repository root.", "", "| step | command | writes | last run |", "|---|---|---|---|"]
    ran = manifest()
    for s in STEPS:
        env = " ".join(f"{k}={v}" for k, v in s["env"].items())
        cmd = (env + " " if env else "") + " ".join(".venv/bin/python" if x == sys.executable else x for x in s["cmd"])
        r = ran.get(s["name"])
        last = f"{r['finished']} ({r['mode']}, {r['seconds']:.0f} s{'' if r['ok'] else ', FAILED'})" if r else \
            ("not run (long job)" if s["long"] else "not run")
        L.append(f"| {s['name']}{' (long)' if s['long'] else ''} | `{cmd}` | {', '.join(s['writes'])} | {last} |")
    open(os.path.join(RES, "CLAIMS.md"), "w").write("\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--compare-figures", action="store_true", help="only compare Fig. 1 and 2 with paper/figures/")
    a = ap.parse_args()
    if a.compare_figures:
        compare_figures()
        return
    define()
    ran = manifest()
    rows = sorted((evaluate(c, ran) for c in CLAIMS), key=lambda r: r["line"] or 10 ** 6)
    machine = None
    try:
        m = J("results/runtime.json")["machine"]
        machine = f"{m['cpu']}, {m['cores']} logical cores, Python {m['python']}, numba {m['numba']}"
    except Missing:
        pass
    meta = dict(generated=time.strftime("%Y-%m-%d %H:%M"), paper="paper/main.tex", machine=machine,
                statuses=list(STATUSES), counts={s: sum(r["status"] == s for r in rows) for s in STATUSES})
    json.dump(dict(meta=meta, claims=rows), open(os.path.join(RES, "claims.json"), "w"), indent=1)
    write_md(rows, meta)
    print(f"{len(rows)} numbers: " + ", ".join(f"{meta['counts'][s]} {s}" for s in STATUSES))
    for r in rows:
        if r["status"] == "differs":
            print(f"  differs  main.tex:{r['line']}  {r['where']}: printed {r['printed']}, regenerated "
                  f"{r['regenerated_str']}")
    print("-> results/claims.json, results/CLAIMS.md")


if __name__ == "__main__":
    main()
