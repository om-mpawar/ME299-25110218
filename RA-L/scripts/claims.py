def parse(printed):
    if "--" in printed:
        lo, hi = printed.split("--")
        return float(lo), float(hi)
    return float(printed)


def decimals(s):
    return len(s.split(".")[1]) if "." in s else 0


def fmt(v, printed):
    if isinstance(v, float) and v == round(v) and "." not in printed and printed.isdigit():
        return f"{v:.0f}"
    d = decimals(printed.split("--")[-1]) + 1 if any(ch.isdigit() for ch in printed) else 2
    if isinstance(v, tuple):
        return "--".join(fmt(x, printed) for x in v)
    if abs(v) >= 100:
        return f"{v:.0f}"
    if abs(v) < 1e-3 and v != 0:
        return f"{v:.1e}"
    return f"{v:.{min(d, 4)}f}"


def manifest():
    try:
        return json.load(open(os.path.join(RES, "logs", "last_run.json")))["steps"]
    except (OSError, ValueError, KeyError):
        return {}


def evaluate(c, ran):
    out = dict(where=c["where"], line=find_line(c["tex"], c["occurrence"]), context=c["tex"].replace("\n", " "),
               printed=c["printed"], regenerated=None, regenerated_str="", delta=None, status=None,
               step=c["step"], command=None, source=c["source"], regenerated_in_last_run=None, note=None)
    step = next((s for s in STEPS if s["name"] == c["step"]), None)
    if step:
        env = " ".join(f"{k}={v}" for k, v in step["env"].items())
        out["command"] = (env + " " if env else "") + " ".join(
            ".venv/bin/python" if x == sys.executable else x for x in step["cmd"])
        r = ran.get(c["step"])
        out["regenerated_in_last_run"] = bool(r and r.get("ok"))
        out["last_run"] = r
    elif c["value"] is not None:
        out["command"] = "(read from the code / data files; no producer)"
    if out["line"] is None:
        out["status"], out["note"] = "differs", f"snippet not found in paper/main.tex: {c['tex']!r} (the paper changed?)"
        return out
    try:
        note = c["note"]() if callable(c["note"]) else c["note"]
    except Missing as e:
        note = f"(note needs {e})"
    except Exception as e:                                               # a note must never stop the report
        note = f"(note failed: {e!r})"
    out["note"] = note
    if c["value"] is not None:
        try:
            v = c["value"]()
            v = tuple(float(x) for x in v) if isinstance(v, (tuple, list)) else float(v)
            out["regenerated"] = list(v) if isinstance(v, tuple) else v
            out["regenerated_str"] = fmt(v, c["printed"]) if c["printed"] not in ("figure",) else (
                "pixel-identical" if v == 1.0 else "differs")
        except Missing as e:
            out["regenerated_str"] = f"(missing: {e})"
            if c["status"] is None:
                out["status"] = "not reproducible here"
                why = f"result file {e} missing"
                if step and step.get("needs"):
                    why += f" (step {c['step']} needs {step['needs']})"
                elif c["step"] == "fem_mass":
                    why = (f"the FEM mesh {e} is not in the repository (data/README.md: copy the std6 meshes into "
                           "data/meshes/ and rerun scripts/reproduce.py --only fem_mass claims)")
                else:
                    why += f" (run: scripts/reproduce.py --only {c['step']})"
                out["note"] = why + (". " + note if note else "")
                return out
    if c["text"] is not None:
        try:
            out["regenerated_str"] = c["text"]()
        except Missing as e:
            out["regenerated_str"] = f"(missing: {e})"
    if c["status"]:
        out["status"] = c["status"]
        return out
    if c["printed"] == "figure":
        out["status"] = "reproduced" if out["regenerated"] == 1.0 else "differs"
        return out
    p = parse(c["printed"])
    v = out["regenerated"]
    pv = p if isinstance(p, tuple) else (p,)
    vv = tuple(v) if isinstance(v, list) else (v,)
    if c["rel"] is not None:
        ok = all(abs(a - b) <= c["rel"] * abs(a) for a, b in zip(pv, vv))
    else:
        tol = c["tol"] if c["tol"] is not None else 0.5 * 10 ** -decimals(c["printed"].split("--")[-1]) + 1e-9
        if isinstance(p, tuple):
            tol_lo = c["tol"] if c["tol"] is not None else 0.5 * 10 ** -decimals(c["printed"].split("--")[0]) + 1e-9
            ok = abs(pv[0] - vv[0]) <= tol_lo and abs(pv[1] - vv[1]) <= tol
        else:
            ok = abs(pv[0] - vv[0]) <= tol
    out["delta"] = [b - a for a, b in zip(pv, vv)] if len(pv) > 1 else vv[0] - pv[0]
    out["status"] = "reproduced" if ok else "differs"
    if step and step["long"] and not out["regenerated_in_last_run"] and c["step"] == "n_transfer":
        out["note"] = ("From results/n_transfer.json, the full run of 2 Nov 2026 (packaged code d51a007, ~2 h); not "
                       "repeated by this run (scripts/reproduce.py --full does). " + (out["note"] or "")).strip()
    if step and step["long"] and not out["regenerated_in_last_run"] and c["step"].startswith("pinn"):
        out["status"] = "stored, not re-run"
        out["note"] = (f"Stored value {'matches' if ok else 'DIFFERS FROM'} the paper. " + (out["note"] or "")).strip()
    return out


