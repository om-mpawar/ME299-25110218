class Missing(Exception):
    pass


_cache = {}


def J(rel):
    """A result file (path relative to the repository root), cached; Missing if it does not exist."""
    if rel not in _cache:
        p = os.path.join(ROOT, rel)
        if not os.path.exists(p):
            raise Missing(rel)
        _cache[rel] = json.load(open(p))
    return _cache[rel]


def poses(tag):
    """Settled poses of an FEM set, as every producer loads it (tdcr.compliance.load_set)."""
    from tdcr.compliance import load_set
    return len(load_set(tag)["C"])


def configs_rows(tag):
    """Rows of the command design of an FEM set (results/configs_std6_<n>s_<kind>.csv)."""
    m = re.match(r"std6_(\d)s_sym_(train|test|rand)", tag)
    path = os.path.join(RES, f"configs_std6_{m.group(1)}s_{m.group(2)}.csv")
    return sum(1 for line in open(path) if line.strip()) - 1


# ---------------------------------------------------------------------------------------------------- helpers
def mc(kind, tag, key="tip"):
    return J("results/mc_std6.json")[kind][tag][key]


def nt(tag, model="+L3 local (output)", key="tip"):
    return J("results/n_transfer.json")["tests"][tag]["models"][model][key]


def props(*keys):
    x = J("results/physics_props.json")
    for k in keys:
        x = x[k]
    return x


def sg_time(n, mount, col):
    """results/study_guide/numbers.json run times: col 2 = median, 3 = p95 (ms)."""
    for row in J("results/study_guide/numbers.json")["time"]:
        if row[0] == n and row[1] == mount:
            return row[col]
    raise Missing("results/study_guide/numbers.json (time)")


def rt(n, mount, key):
    for row in J("results/runtime.json")["twin"]:
        if row["n"] == n and row["mounting"] == mount:
            return row[key]
    raise Missing("results/runtime.json")


