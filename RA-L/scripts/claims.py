def compare_figures():
    import matplotlib.image as mpimg
    os.makedirs(os.path.join(RES, "figures"), exist_ok=True)
    res = {}
    for name in ("fig_profile", "fig_transfer"):
        a, b = os.path.join(RES, "figures", name + ".pdf"), os.path.join(ROOT, "paper", "figures", name + ".pdf")
        if not os.path.exists(a):
            res[name] = dict(identical=False, why=f"{os.path.relpath(a, ROOT)} missing")
            continue
        with tempfile.TemporaryDirectory() as tmp:
            imgs = []
            for k, p in enumerate((a, b)):
                subprocess.run(["pdftoppm", "-r", "150", "-png", "-singlefile", p, os.path.join(tmp, str(k))], check=True)
                imgs.append(mpimg.imread(os.path.join(tmp, f"{k}.png")))
        same_shape = imgs[0].shape == imgs[1].shape
        diff = np.abs(imgs[0] - imgs[1]) if same_shape else None
        res[name] = dict(identical=bool(same_shape and diff.max() == 0), shape=list(imgs[0].shape),
                         max_abs_diff=float(diff.max()) if same_shape else None,
                         differing_pixels=int((diff.max(-1) > 0).sum()) if same_shape else None, dpi=150)
        print(f"{name}: {'pixel-identical' if res[name]['identical'] else 'DIFFERS'} at 150 dpi")
    json.dump(res, open(os.path.join(RES, "figures", "compare.json"), "w"), indent=1)


